// Replace literal '/Users/drew' occurrences in bundled source files with
// generic equivalents. Targets are exclusively comments and guard-string
// literals — none are functional runtime paths.
//   Guards: raw.includes('/Users/drew') → raw.includes('/Users/')
//   Comments/messages: /Users/drew → /Users/<machine>
function scrubDevMachineStrings() {
  const targets = [
    'sync_iteration_v1_workflows_to_db.mjs',
    join('scripts', 'bootstrap-ai-video-workflows.mjs'),
    join('版本测试', 'serve-review-assets.mjs'),
  ];
  let patched = 0;
  for (const rel of targets) {
    const full = join(appResources, rel);
    if (!existsSync(full)) continue;
    let content;
    try { content = readFileSync(full, 'utf8'); } catch { continue; }
    if (!content.includes('/Users/drew')) continue;
    const updated = content
      .replace(/raw\.includes\('\/Users\/drew'\)/g, "raw.includes('/Users/')")
      .replace(/\/Users\/drew/g, '/Users/<machine>');
    if (updated !== content) {
      writeFileSync(full, updated);
      patched += 1;
    }
  }
  console.log(`scrubDevMachineStrings: patched ${patched} files`);
}

// Remove native-addon build metadata that embeds build-machine absolute paths.
// These files (config.gypi, Makefile, *.mk, *.d, *.d.raw) are only needed for
// `npm rebuild` and are never loaded at runtime. The compiled .node binaries are kept.
function scrubNativeBuildMetadata() {
  const nmDir = join(appResources, 'node_modules');
  if (!existsSync(nmDir)) return;
  const BUILD_META = /^(config\.gypi|Makefile|.+\.mk|.+\.d|.+\.d\.raw)$/;
  let removed = 0;
  function walk(dir) {
    let entries;
    try { entries = readdirSync(dir); } catch { return; }
    for (const entry of entries) {
      const full = join(dir, entry);
      let st;
      try { st = lstatSync(full); } catch { continue; }
      if (st.isSymbolicLink()) continue;
      if (st.isDirectory()) { walk(full); continue; }
      if (!BUILD_META.test(entry)) continue;
      let content;
      try { content = readFileSync(full, 'utf8'); } catch { continue; }
      if (content.includes('/Users/')) {
        unlinkSync(full);
        removed += 1;
      }
    }
  }
  walk(nmDir);
  console.log(`scrubNativeBuildMetadata: removed ${removed} build-machine path files`);
}

// Remove build-tool log files left behind by turbo/lint/other build steps.
// These are never needed at runtime and may contain absolute paths.
function scrubBuildLogs() {
  const appDir = appResources;
  if (!existsSync(appDir)) return;
  let removed = 0;
  function walk(dir) {
    let entries;
    try { entries = readdirSync(dir); } catch { return; }
    for (const entry of entries) {
      const full = join(dir, entry);
      let st;
      try { st = lstatSync(full); } catch { continue; }
      if (st.isSymbolicLink()) continue;
      if (st.isDirectory()) { walk(full); continue; }
      if (entry.endsWith('.log')) {
        try { unlinkSync(full); removed += 1; } catch {}
      }
    }
  }
  walk(appDir);
  console.log(`scrubBuildLogs: removed ${removed} log files`);
}

// Remove __pycache__ directories left by node-gyp / Python-based build tools.
// These contain .pyc bytecache that embeds build-machine absolute paths.
function scrubPycache() {
  const nmDir = join(appResources, 'node_modules');
  if (!existsSync(nmDir)) return;
  let removed = 0;
  function walk(dir) {
    let entries;
    try { entries = readdirSync(dir); } catch { return; }
    for (const entry of entries) {
      const full = join(dir, entry);
      let st;
      try { st = lstatSync(full); } catch { continue; }
      if (st.isSymbolicLink()) continue;
      if (st.isDirectory()) {
        if (entry === '__pycache__') {
          try { rmSync(full, { recursive: true, force: true }); removed += 1; } catch {}
        } else {
          walk(full);
        }
      }
    }
  }
  walk(nmDir);
  console.log(`scrubPycache: removed ${removed} __pycache__ directories`);
}

// Remove native-addon compile intermediates (obj.target dirs and *.a static libs).
// These are only needed for `npm rebuild` and embed build-machine absolute paths.
function scrubNativeBuildArtifacts() {
  const nmDir = join(appResources, 'node_modules');
  if (!existsSync(nmDir)) return;
  let removed = 0;
  function walk(dir) {
    let entries;
    try { entries = readdirSync(dir); } catch { return; }
    for (const entry of entries) {
      const full = join(dir, entry);
      let st;
      try { st = lstatSync(full); } catch { continue; }
      if (st.isSymbolicLink()) continue;
      if (st.isDirectory()) {
        if (entry === 'obj.target') {
          try { rmSync(full, { recursive: true, force: true }); removed += 1; } catch {}
        } else {
          walk(full);
        }
      } else if (entry.endsWith('.a') && full.includes('/build/')) {
        try { unlinkSync(full); removed += 1; } catch {}
      }
    }
  }
  walk(nmDir);
  console.log(`scrubNativeBuildArtifacts: removed ${removed} compile intermediates`);
}

function bundleNodeRuntime() {
  let nodeBin = '';
  try {
    nodeBin = execFileSync('/usr/bin/env', ['which', 'node'], { encoding: 'utf8' }).trim();
  } catch {}
  if (!nodeBin || !existsSync(nodeBin)) {
    console.warn('未找到本机 node，打包继续；目标机器需要自行安装 Node.js 18+。');
    return;
  }
  const binDir = join(appResources, 'bin');
  mkdirSync(binDir, { recursive: true });
  cpSync(nodeBin, join(binDir, 'node'), { dereference: true });
  execFileSync('/bin/chmod', ['755', join(binDir, 'node')]);
  console.log(`bundled node runtime (${basename(nodeBin)})`);
}

function relinkAbsoluteSymlinks(dir) {
  let changed = 0;
  let removedBroken = 0;
  function walk(current) {
    let stat;
    try {
      stat = lstatSync(current);
    } catch {
      return;
    }
    if (stat.isSymbolicLink()) {
      const target = readlinkSync(current);
      if (target.startsWith(root)) {
        const targetInsideApp = join(appResources, relative(root, target));
        const relativeTarget = relative(dirname(current), targetInsideApp);
        unlinkSync(current);
        symlinkSync(relativeTarget, current);
        changed += 1;
      }
      try {
        if (!existsSync(current)) {
          unlinkSync(current);
          removedBroken += 1;
        }
      } catch {}
      return;
    }
    if (!stat.isDirectory()) return;
    for (const entry of readdirSync(current)) {
      walk(join(current, entry));
    }
  }
  walk(dir);
  console.log(`rewrote absolute symlinks: ${changed}`);
  console.log(`removed broken symlinks: ${removedBroken}`);
}

// Install the custom AI Video app icon into the bundle. The ditto of Electron.app
// preserves Contents/Resources (with the default electron.icns); we copy our
// generated build/icon.icns alongside it and repoint Info.plist at it later.
// If the icon source is missing, packaging continues with the Electron default.
function installAppIcon() {
  if (!existsSync(customAppIcon)) {
    console.warn('未找到 build/icon.icns，App 将使用 Electron 默认图标。');
    console.warn('如需自定义图标，请先运行：node scripts/generate-app-icon.mjs');
    return false;
  }
  cpSync(customAppIcon, join(resources, 'icon.icns'));
  console.log('installed app icon: Contents/Resources/icon.icns');
  return true;
}

function adHocSignApp() {
  try {
    execFileSync('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', outApp], { stdio: 'inherit' });
    console.log('ad-hoc signed app bundle');
  } catch (error) {
    console.warn('ad-hoc signing failed; macOS may show the app as damaged on downloaded machines.');
    throw error;
  }
}

if (!existsSync(electronApp)) {
  console.error(`找不到 Electron 运行时：${electronApp}`);
  console.error('请先运行：ELECTRON_MIRROR=https://npmmirror.com/mirrors/electron/ npm rebuild electron');
  process.exit(1);
}

rmSync(outApp, { recursive: true, force: true });
mkdirSync(join(outApp, 'Contents'), { recursive: true });
execFileSync('/usr/bin/ditto', [electronApp, outApp], { stdio: 'inherit' });

rmSync(appResources, { recursive: true, force: true });
mkdirSync(appResources, { recursive: true });

for (const item of include) {
  const src = join(root, item);
  if (!existsSync(src)) continue;
  cpSync(src, join(appResources, item), { recursive: true, filter });
  console.log(`copied ${item}`);
}

sanitizeConfig('config/local-config.json');
sanitizeConfig('版本测试/config/local-config.json');
removeRuntimeArtifacts();
removeLegacyWorkflowArtifacts();
bundleNodeRuntime();
relinkAbsoluteSymlinks(join(appResources, 'node_modules'));
scrubNativeBuildMetadata();
scrubBuildLogs();
scrubDevMachineStrings();
scrubPycache();
scrubNativeBuildArtifacts();
const appIconInstalled = installAppIcon();

writeFileSync(
  join(appResources, 'README-AI-Video-Mac-App.txt'),
  [
    'AI Video — Mac 本地 App 测试版',
    '',
    '双击 dist/AI Video.app 即可启动。',
    '',
    '说明：',
    '- 这是本地测试版 App，尚未签名、公证。',
    '- 第一次打开如果 macOS 提示无法验证，请右键 App 选择「打开」。',
    '- 首次打开需要激活：复制设备 ID 给销售/客服，拿到激活码后粘贴激活。',
    '- 当前包已内置 Node.js 运行时；如遇安全拦截，请右键 App 选择「打开」。',
    '- n8n 与 UI 会在后台自动启动，用户主要操作 AI Video 窗口。',
    '',
  ].join('\n'),
);

const infoPlist = join(outApp, 'Contents', 'Info.plist');
if (existsSync(infoPlist)) {
  let plist = await import('node:fs').then(({ readFileSync }) => readFileSync(infoPlist, 'utf8'));
  plist = plist
    .replace(/(<key>CFBundleName<\/key>\s*)<string>Electron<\/string>/, '$1<string>AI Video</string>')
    .replace(/(<key>CFBundleDisplayName<\/key>\s*)<string>Electron<\/string>/, '$1<string>AI Video</string>')
    .replace(/(<key>CFBundleShortVersionString<\/key>\s*)<string>[^<]+<\/string>/, '$1<string>1.0.0</string>')
    .replace(/(<key>CFBundleVersion<\/key>\s*)<string>[^<]+<\/string>/, '$1<string>1.0.0</string>')
    .replace(/<string>com\.github\.Electron<\/string>/g, '<string>com.aivideo.workbench</string>');
  // Point the bundle at the custom icon when it was installed; otherwise keep
  // the Electron default so packaging never breaks on a missing icon.
  if (appIconInstalled) {
    plist = plist.replace(
      /(<key>CFBundleIconFile<\/key>\s*)<string>[^<]*<\/string>/,
      '$1<string>icon.icns</string>',
    );
  }
  writeFileSync(infoPlist, plist);
}

// One final sweep immediately before signing. If a local test process wrote
// runtime logs into a previous bundle, those files would invalidate the seal.
removeRuntimeArtifacts();
adHocSignApp();

console.log('');
console.log('AI Video Mac App ready:');
console.log(outApp);
