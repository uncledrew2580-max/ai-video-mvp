function filter(src) {
  const rel = relative(root, src);
  const parts = rel.split('/');
  const base = parts.at(-1);
  if (base === '.DS_Store') return false;
  // Only exclude project-level generated/runtime folders. Package folders often
  // contain their own dist/ directories, and n8n cannot run without them.
  if (parts.length === 1 && excluded.has(base)) return false;
  if (parts[0] === 'dist' || parts[0] === 'logs') return false;
  if (parts.includes('.n8n-local-cache') || parts.includes('.n8n-local-cache-backups')) return false;
  if (parts[0] === '版本测试' && parts[1] === 'logs') return false;
  // Exclude legacy/test/dev-only artifacts from 版本测试
  if (parts[0] === '版本测试' && parts[1] === 'backups') return false;
  if (parts[0] === '版本测试' && parts[1] === '正式导入文件') return false;
  if (parts[0] === '版本测试' && base === 'concept-select-workflow.json') return false;
  if (parts[0] === '版本测试' && base === 'reset-test-state.mjs') return false;
  if (parts.includes('.git')) return false;
  if (/^node_modules\.broken-/.test(base) && parts.length === 1) return false;

  // Keep runtime smaller. The packaged app already contains Electron itself.
  if (src.includes('/node_modules/electron/')) return false;
  if (src.endsWith('/node_modules/electron')) return false;
  if (src.includes('/node_modules/electron-builder/')) return false;
  if (src.endsWith('/node_modules/electron-builder')) return false;
  if (src.includes('/node_modules/app-builder-bin/')) return false;
  if (src.endsWith('/node_modules/app-builder-bin')) return false;
  // @electron/rebuild is a build-time-only native-addon recompilation tool
  if (src.includes('/node_modules/@electron/rebuild/')) return false;
  if (src.endsWith('/node_modules/@electron/rebuild')) return false;
  // Sentry optional telemetry — native profiler + stack-trace addons are not
  // required for n8n workflow execution and contain build-machine paths in DWARF
  if (src.includes('/node_modules/@sentry-internal/node-cpu-profiler/')) return false;
  if (src.endsWith('/node_modules/@sentry-internal/node-cpu-profiler')) return false;
  if (src.includes('/node_modules/@sentry-internal/node-native-stacktrace/')) return false;
  if (src.endsWith('/node_modules/@sentry-internal/node-native-stacktrace')) return false;

  // n8n 2.x expects @n8n/api-types and n8n-workflow to share one zod
  // instance. Duplicated nested zod copies can break module startup in the
  // packaged runtime with discriminatedUnion errors.
  if (src.includes('/node_modules/@n8n/api-types/node_modules/zod')) return false;
  if (src.includes('/node_modules/n8n-workflow/node_modules/zod')) return false;

  return true;
}

function scrubApiKeys(value) {
  if (Array.isArray(value)) return value.map(scrubApiKeys);
  if (!value || typeof value !== 'object') return value;

  for (const [key, child] of Object.entries(value)) {
    const normalized = key.toLowerCase();
    if (normalized === 'api_key' || normalized.endsWith('_api_key')) {
      value[key] = '';
    } else {
      value[key] = scrubApiKeys(child);
    }
  }
  return value;
}

